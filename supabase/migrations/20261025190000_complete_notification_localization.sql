      WHEN lower(type) LIKE '%annul%' OR lower(type) LIKE '%cancel%' THEN 'canceled'
      WHEN lower(type) LIKE '%accep%' OR lower(type) LIKE '%accepted%' OR lower(type) = 'ami_confirme' THEN 'accepted'
      WHEN lower(type) LIKE '%rejet%' OR lower(type) LIKE '%reject%' THEN 'rejected'
      WHEN lower(type) LIKE '%valide%' OR lower(type) LIKE '%approved%' THEN 'approved'
      WHEN lower(type) LIKE '%demande%' OR lower(type) LIKE '%request%' OR lower(type) LIKE '%join_request%' THEN 'request'
      WHEN lower(type) LIKE 'reponse_invitation%' THEN 'reply'
      WHEN lower(type) LIKE '%invitation%' OR lower(type) LIKE '%invite%' OR lower(type) LIKE '%sponsor%' THEN 'invitation'
      WHEN lower(type) LIKE '%shared_story%' OR lower(type) LIKE '%share%' THEN 'share'
      WHEN lower(type) LIKE '%bienvenue%' OR lower(type) = 'welcome' THEN 'welcome'
      WHEN lower(type) LIKE '%transfert%' OR lower(type) LIKE '%transfer%' THEN 'transfer'
      WHEN lower(type) LIKE '%prix_activite_reduit%' OR lower(type) LIKE '%price_reduced%' THEN 'price_reduced'
      WHEN lower(type) LIKE '%checkin%' THEN 'checkin'
      WHEN lower(type) LIKE '%suppression%' OR lower(type) LIKE '%supprime%' OR lower(type) LIKE '%deletion%' THEN 'deletion'
      WHEN lower(type) LIKE '%pres_de_vous%' OR lower(type) LIKE '%nearby_event%' THEN 'nearby_event'
      WHEN lower(type) LIKE '%promotion%' OR lower(type) LIKE '%co_createur%' OR lower(type) LIKE '%quitte%' OR lower(type) LIKE '%retire%' OR lower(type) LIKE '%assignation%' OR lower(type) LIKE '%staff%' OR lower(type) LIKE '%role_update%' THEN 'role_update'
      WHEN lower(type) LIKE '%modifie%' OR lower(type) LIKE '%event_update%' THEN 'event_update'
      ELSE 'other'
    END AS family
  FROM all_types
  WHERE lower(type) <> 'message_received'
),

INSERT INTO private.notification_templates(type, language, title_template, body_template)
SELECT tf.type, tr.language, tr.title_template, tr.body_template
FROM type_families tf
JOIN translations tr ON tr.family = tf.family
WHERE NOT EXISTS (
  SELECT 1 FROM private.notification_templates existing
  WHERE existing.type = tf.type AND existing.language = tr.language
)
ON CONFLICT (type, language) DO NOTHING;
